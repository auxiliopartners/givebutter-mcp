import { z } from "zod";
import { defineTools } from "./types.js";
import { contactActivityType, writableContactActivityType } from "../types/common.js";

const contact_id = z.number().describe("The contact ID");
const activity_id = z.number().describe("The activity ID");

const editable = {
  note: z.string().max(255).optional().describe("Activity note"),
  subject: z.string().max(255).optional().describe("Activity subject"),
  occurred_at: z.string().optional().describe("When it happened, in ISO 8601 format"),
  timezone: z.string().max(255).optional().describe("Timezone for occurred_at"),
};

export const contactActivityTools = defineTools([
  {
    name: "list_contact_activities",
    description: "List all activities for a contact",
    method: "GET",
    path: "/contacts/:contact_id/activities",
    paginated: true,
    input: {
      contact_id,
      type: contactActivityType.optional().describe("Filter by activity type"),
    },
  },
  {
    name: "get_contact_activity",
    description: "Get details of a specific contact activity",
    method: "GET",
    path: "/contacts/:contact_id/activities/:activity_id",
    input: { contact_id, activity_id },
  },
  {
    name: "create_contact_activity",
    description:
      "Log an activity on a contact, such as a note, meeting, phone call or completed task",
    method: "POST",
    path: "/contacts/:contact_id/activities",
    input: {
      contact_id,
      type: writableContactActivityType.describe(
        "Activity type. Only these seven can be created; the rest are generated by Givebutter.",
      ),
      ...editable,
    },
  },
  {
    name: "update_contact_activity",
    description: "Update an existing contact activity",
    method: "PUT",
    path: "/contacts/:contact_id/activities/:activity_id",
    input: { contact_id, activity_id, ...editable },
  },
  {
    name: "delete_contact_activity",
    description: "Delete a contact activity",
    method: "DELETE",
    path: "/contacts/:contact_id/activities/:activity_id",
    input: { contact_id, activity_id: z.number().describe("The activity ID to delete") },
  },
]);
